/** Hindi copy for a city. Throws at build time if a city has none, so a new English
    city can never ship a half-empty Hindi page. */
export function cityHi(slug: string): CityHi {
  const hi = citiesHi[slug];
  if (!hi) throw new Error(`lib/content-hi.ts: no Hindi copy for city "${slug}"`);
  return hi;
}

/** The four city names joined the Hindi way: "रायपुर, भिलाई, दुर्ग और बिलासपुर". */
export const cityListHi = (() => {
  const names = cities.map((c) => cityHi(c.slug).name);
  return `${names.slice(0, -1).join(', ')} और ${names.at(-1)}`;
})();

